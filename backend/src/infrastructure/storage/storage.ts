import { presignUrl, signHeaders, type Creds } from "./sigv4.js";

/** S3-compatible object storage port. Media never flows through the API: clients upload/download via presigned URLs. */
export interface ObjectStorage {
  presignPut(key: string, o: { contentType: string; expiresS: number }): Promise<{ url: string; headers: Record<string, string> }>;
  presignGet(key: string, expiresS: number): Promise<string>;
  head(key: string): Promise<{ size: number; contentType: string | null } | null>;
  readRange(key: string, start: number, endInclusive: number): Promise<Uint8Array>;
  delete(key: string): Promise<void>;
  /** Server-side upload (for derived files generated by the backend itself). */
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
}

export interface R2Config { accountId: string; accessKeyId: string; secretAccessKey: string; bucket: string }

export function createR2Storage(cfg: R2Config, f: typeof fetch = fetch): ObjectStorage {
  const creds: Creds = { accessKeyId: cfg.accessKeyId, secretAccessKey: cfg.secretAccessKey, region: "auto" };
  const url = (key: string) => `https://${cfg.accountId}.r2.cloudflarestorage.com/${cfg.bucket}/${key.split("/").map(encodeURIComponent).join("/")}`;
  return {
    async presignPut(key, { contentType, expiresS }) {
      return { url: await presignUrl(creds, "PUT", url(key), expiresS, { signedHeaders: { "content-type": contentType, "if-none-match": "*" } }), headers: { "Content-Type": contentType, "If-None-Match": "*" } };   // create-only: the URL cannot overwrite an object after confirm verified it
    },
    presignGet: (key, expiresS) => presignUrl(creds, "GET", url(key), expiresS),
    async head(key) {
      const res = await f(url(key), { method: "HEAD", headers: await signHeaders(creds, "HEAD", url(key)) });
      if (res.status === 404) return null;
      if (!res.ok) throw new Error(`storage HEAD ${res.status}`);
      return { size: Number(res.headers.get("content-length") ?? 0), contentType: res.headers.get("content-type") };
    },
    async readRange(key, start, end) {
      const res = await f(url(key), { headers: await signHeaders(creds, "GET", url(key), { range: `bytes=${start}-${end}` }) });
      if (!res.ok) throw new Error(`storage GET ${res.status}`);
      return new Uint8Array(await res.arrayBuffer());
    },
    async put(key, body, contentType) {
      const res = await f(url(key), { method: "PUT", headers: await signHeaders(creds, "PUT", url(key), { "content-type": contentType }, new Date(), body), body });   // content-type is already part of the signed headers
      if (!res.ok) throw new Error(`storage PUT ${res.status}`);
    },
    async delete(key) {
      const res = await f(url(key), { method: "DELETE", headers: await signHeaders(creds, "DELETE", url(key)) });
      if (!res.ok && res.status !== 404) throw new Error(`storage DELETE ${res.status}`);
    },
  };
}
